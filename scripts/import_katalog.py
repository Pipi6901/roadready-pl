# -*- coding: utf-8 -*-
"""Turns the ministry's question catalogue into the app's content bundle.

Input:  KATALOG_dla_kandydatów_na_kierowców_MMYYYY.xlsx from
        https://www.gov.pl/web/infrastruktura/prawo-jazdy
Output: content/katalog/content.json — the exact payload shape the mobile app
        fetches (src/data/remoteContent.ts) and the admin seeds from
        (roadready-admin-pl/scripts/seed.js), plus a review CSV.

What the catalogue gives us and what it does not:
- 3.5k questions with the exam class (basic/specialist), the point weight, the
  licence categories each question applies to, and the media file the
  question refers to. Official translations into English, German and
  Ukrainian ride along in the same row.
- No thematic sections (assigned here, see katalog_topics.py), no
  explanations (left empty — the exam has none, the app treats an empty
  explanation as "show only the correct answer"), and no media files: those
  are a separate 9.5 GB archive on the same page, handled by a later step. The
  original file name is kept in `sourceMedia` so that step can match them.
- Translations only into the exam languages. Russian, Spanish and Turkish, and
  the third of the bank Ukrainian lacks, are generated by the admin repo's
  scripts/translate-questions.js into content/katalog/translations/{lang}.json
  and merged here — an official translation always wins over a generated one.
  Hand-written chunks in content/katalog/translations/{lang}/NNN.json are
  merged the same way (see normalise_entry for the compact form).
- Explanations are written by us, not the ministry: content/katalog/
  explanations/{lang}.json or explanations/{lang}/NNN.json, { "q-123": "text" }.
  `pl` fills the question's own `explanation`; every other language fills the
  `explanation` of that language's translation entry (the entry must exist).

Usage: python scripts/import_katalog.py <catalogue.xlsx>
"""
import csv
import io
import json
import os
import re
import sys
from collections import Counter, defaultdict

from openpyxl import load_workbook

sys.path.insert(0, os.path.dirname(__file__))
from katalog_topics import classify  # noqa: E402

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8', errors='replace')

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, 'content', 'katalog')

# Column indexes in the catalogue sheet (0-based).
COL = dict(lp=0, number=1, text=2, a=3, b=4, c=5, correct=6, media=7, structure=8, points=9, categories=10,
           en_text=15, en_a=16, en_b=17, en_c=18, de_text=19, de_a=20, de_b=21, de_c=22, ua_text=23, ua_a=24, ua_b=25, ua_c=26)

LICENCE_ORDER = ['AM', 'A1', 'A2', 'A', 'B1', 'B', 'C1', 'C', 'D1', 'D', 'T', 'PT']

YES_NO = {'en': ('Yes', 'No'), 'de': ('Ja', 'Nein'), 'uk': ('Так', 'Ні'), 'ru': ('Да', 'Нет'), 'es': ('Sí', 'No'), 'tr': ('Evet', 'Hayır')}


def clean(value):
    if value is None:
        return ''
    s = str(value).replace(' ', ' ').strip()
    return re.sub(r'\s+', ' ', s)


# Optional columns, located by header: the ES/TR translations and the
# per-language explanations added to the July 2026 file by our translator
# (KATALOG_…_ES_TR_wyjasnienia.xlsx). Absent in the ministry's own file.
EXTRA_HEADERS = {
    'es_text': 'Pytanie [ES]', 'es_a': 'Odpowiedź A [ES]', 'es_b': 'Odpowiedź B [ES]', 'es_c': 'Odpowiedź C [ES]',
    'tr_text': 'Pytanie [TR]', 'tr_a': 'Odpowiedź A [TR]', 'tr_b': 'Odpowiedź B [TR]', 'tr_c': 'Odpowiedź C [TR]',
    'expl_pl': 'Wyjaśnienie [PL]', 'expl_en': 'Wyjaśnienie [EN]', 'expl_de': 'Wyjaśnienie [D]',
    'expl_uk': 'Wyjaśnienie [UA]', 'expl_ru': 'Wyjaśnienie [RU]', 'expl_es': 'Wyjaśnienie [ES]', 'expl_tr': 'Wyjaśnienie [TR]',
}
XLSX_LOCALES = {'en': ('en_text', 'en_a', 'en_b', 'en_c'), 'de': ('de_text', 'de_a', 'de_b', 'de_c'),
                'uk': ('ua_text', 'ua_a', 'ua_b', 'ua_c'), 'es': ('es_text', 'es_a', 'es_b', 'es_c'),
                'tr': ('tr_text', 'tr_a', 'tr_b', 'tr_c')}


def load_rows(path):
    wb = load_workbook(path, read_only=True, data_only=True)
    ws = wb['katalog']
    rows = []
    for i, r in enumerate(ws.iter_rows(values_only=True)):
        if i == 0:
            header = {clean(c): j for j, c in enumerate(r) if c is not None}
            for key, title in EXTRA_HEADERS.items():
                if title in header:
                    COL[key] = header[title]
            continue
        if clean(r[COL['number']]) == '':
            continue
        rows.append(r)
    return rows


def cell(r, key):
    j = COL.get(key)
    return clean(r[j]) if j is not None and j < len(r) else ''


def structure_of(raw):
    s = clean(raw).upper()
    if s.startswith('PODST'):
        return 'basic'
    # "SPECJALISTYCZNY", "Specjalistyczny", and one "Specajlistyczny" in the July 2026 file.
    return 'specialist'


def build(rows, topics_meta):
    questions, translations = [], {loc: {} for loc, cols in XLSX_LOCALES.items() if cols[0] in COL}
    explanations = {loc: {} for loc in ('pl', 'en', 'de', 'uk', 'ru', 'es', 'tr') if f'expl_{loc}' in COL}
    problems = []
    for r in rows:
        number = clean(r[COL['number']])
        qid = f'q-{number}'
        text = clean(r[COL['text']])
        structure = structure_of(r[COL['structure']])
        correct = clean(r[COL['correct']]).upper()
        # Ten rows in the July 2026 file carry the wrong class label: a
        # TAK/NIE answer under SPECJALISTYCZNY or three lettered options under
        # PODSTAWOWY. The answer format is what the exam actually shows the
        # candidate, so it wins over the label.
        if correct in ('T', 'N'):
            structure = 'basic'
        elif correct in ('A', 'B', 'C'):
            structure = 'specialist'
        points = int(float(clean(r[COL['points']]) or 1))
        licences = [c.strip().upper() for c in clean(r[COL['categories']]).split(',') if c.strip()]
        licences = [c for c in LICENCE_ORDER if c in licences]
        media = clean(r[COL['media']]) or None

        if structure == 'basic':
            if correct not in ('T', 'N'):
                problems.append((qid, f'basic answer {correct!r}'))
                continue
            options = [{'id': 'T', 'text': 'TAK'}, {'id': 'N', 'text': 'NIE'}]
        else:
            a, b, c = clean(r[COL['a']]), clean(r[COL['b']]), clean(r[COL['c']])
            if correct not in ('A', 'B', 'C') or not (a and b and c):
                problems.append((qid, f'specialist answer {correct!r} options {bool(a)}/{bool(b)}/{bool(c)}'))
                continue
            options = [{'id': 'A', 'text': a}, {'id': 'B', 'text': b}, {'id': 'C', 'text': c}]

        answers_blob = ' '.join(o['text'] for o in options) if structure == 'specialist' else ''
        topic = classify(structure, text, answers_blob, media is not None)

        questions.append({
            'id': qid,
            'topicId': topic,
            'type': 'single_choice',
            'text': text,
            'options': options,
            'correctOptionId': correct,
            'explanation': cell(r, 'expl_pl'),
            'mediaId': None,
            'sourceMedia': media,
            'subtopic': None,
            'sourceRef': f'Katalog MI 07/2026, pytanie nr {number}',
            'category': structure,
            'points': points,
            'licences': licences,
        })

        for loc in explanations:
            if loc != 'pl' and cell(r, f'expl_{loc}'):
                explanations[loc][qid] = cell(r, f'expl_{loc}')

        for loc, (tk, ak, bk, ck) in XLSX_LOCALES.items():
            if loc not in translations:
                continue
            t = cell(r, tk)
            if not t:
                continue
            if structure == 'basic':
                yes, no = YES_NO[loc]
                opts = {'T': yes, 'N': no}
            else:
                oa, ob, oc = cell(r, ak), cell(r, bk), cell(r, ck)
                if not (oa and ob and oc):
                    continue
                opts = {'A': oa, 'B': ob, 'C': oc}
            translations[loc][qid] = {'text': t, 'options': opts, 'explanation': ''}

    return questions, translations, explanations, problems


def generated_files(gen_dir):
    """(locale, path) for translations/{lang}.json and translations/{lang}/*.json chunks."""
    out = []
    for name in sorted(os.listdir(gen_dir)):
        full = os.path.join(gen_dir, name)
        if name.endswith('.json'):
            out.append((name[:-5], full))
        elif os.path.isdir(full):
            for chunk in sorted(os.listdir(full)):
                if chunk.endswith('.json'):
                    out.append((name, os.path.join(full, chunk)))
    return out


def normalise_entry(q, tr):
    """Accepts the verbose {text, options} form and the compact one used by
    hand-written chunks: a bare string for a yes/no question, or
    [text, A, B, C] for one with options."""
    if isinstance(tr, str):
        return {'text': tr, 'options': {}}
    if isinstance(tr, list):
        opts = {o['id']: v for o, v in zip(q['options'], tr[1:])}
        return {'text': tr[0], 'options': opts}
    return {'text': tr.get('text', ''), 'options': tr.get('options', {})}


def merge_generated(questions, translations):
    """Fills the gaps in `translations` from the generated files — an official
    translation always wins; the first generated file to cover an id wins next."""
    gen_dir = os.path.join(OUT_DIR, 'translations')
    if not os.path.isdir(gen_dir):
        return {}
    ids = {q['id']: q for q in questions}
    added = Counter()
    for loc, path in generated_files(gen_dir):
        with open(path, encoding='utf-8') as f:
            gen = json.load(f)
        target = translations.setdefault(loc, {})
        for qid, raw in gen.items():
            q = ids.get(qid)
            if q is None or qid in target:
                continue
            tr = normalise_entry(q, raw)
            if not tr['text']:
                continue
            if q['category'] == 'basic':
                yes, no = YES_NO.get(loc, ('', ''))
                opts = {'T': yes, 'N': no} if yes else {}
            else:
                opts = {o['id']: tr['options'].get(o['id'], '') for o in q['options']}
                if not all(opts.values()):
                    continue
            target[qid] = {'text': tr['text'], 'options': opts, 'explanation': ''}
            added[loc] += 1
    return dict(added)


def merge_explanations(questions, translations, from_xlsx=None):
    """Fills `explanation` — first from the catalogue's own explanation columns
    (`from_xlsx`, {lang: {id: text}}, the translator's file), then from
    content/katalog/explanations/{lang}[.json|/*.json] for whatever is still
    empty. Returns {lang: count}; ids that are unknown or (for a translation)
    have no translation entry yet are reported and skipped."""
    sources = [(loc, gen) for loc, gen in (from_xlsx or {}).items()]
    exp_dir = os.path.join(OUT_DIR, 'explanations')
    if os.path.isdir(exp_dir):
        for loc, path in generated_files(exp_dir):
            with open(path, encoding='utf-8') as f:
                sources.append((loc, json.load(f)))
    ids = {q['id']: q for q in questions}
    added, skipped = Counter(), Counter()
    for loc, gen in sources:
        for qid, text in gen.items():
            text = (text or '').strip()
            q = ids.get(qid)
            if q is None or not text:
                skipped[loc] += 1
                continue
            if loc == 'pl':
                if not q['explanation']:
                    q['explanation'] = text
                    added[loc] += 1
                continue
            entry = translations.get(loc, {}).get(qid)
            if entry is None:
                skipped[loc] += 1
                continue
            if not entry.get('explanation'):
                entry['explanation'] = text
                added[loc] += 1
    if skipped:
        print(f'explanations skipped (unknown id / no translation yet): {dict(skipped)}')
    return dict(added)


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    src = sys.argv[1]
    rows = load_rows(src)

    # Topic metadata comes from the app's own list so ids and names cannot drift.
    with open(os.path.join(ROOT, 'content', 'katalog', 'topics.json'), encoding='utf-8') as f:
        topics_meta = json.load(f)
    with open(os.path.join(ROOT, 'content', 'katalog', 'country.json'), encoding='utf-8') as f:
        country = json.load(f)
    with open(os.path.join(ROOT, 'content', 'katalog', 'locales.json'), encoding='utf-8') as f:
        locales = json.load(f)

    questions, translations, xlsx_expl, problems = build(rows, topics_meta)
    generated = merge_generated(questions, translations)
    explained = merge_explanations(questions, translations, xlsx_expl)

    counts = Counter(q['topicId'] for q in questions)
    topics = []
    for t in topics_meta:
        topics.append({**t, 'questionCount': counts.get(t['id'], 0)})

    country = {**country, 'questionCount': len(questions)}
    payload = {
        'country': country,
        'topics': topics,
        'questions': questions,
        'translations': translations,
        'media': {},
        'versionHash': f'katalog-{os.path.basename(src).rsplit("_", 1)[-1].split(".")[0]}-{len(questions)}',
        'countries': [country],
        'locales': locales,
    }
    os.makedirs(OUT_DIR, exist_ok=True)
    out = os.path.join(OUT_DIR, 'content.json')
    with open(out, 'w', encoding='utf-8') as f:
        json.dump(payload, f, ensure_ascii=False, separators=(',', ':'))

    # Review sheet: one row per question with the assigned topic, for eyeballing.
    with open(os.path.join(OUT_DIR, 'review.csv'), 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.writer(f, delimiter=';')
        w.writerow(['id', 'class', 'points', 'topic', 'licences', 'media', 'text'])
        for q in questions:
            w.writerow([q['id'], q['category'], q['points'], q['topicId'], ','.join(q['licences']), q['sourceMedia'] or '', q['text']])

    print(f'questions: {len(questions)}  skipped: {len(problems)}  size: {os.path.getsize(out) / 1e6:.1f} MB')
    for qid, why in problems[:10]:
        print('  skipped', qid, why)
    print('translations:', {k: len(v) for k, v in translations.items()}, 'generated:', generated)
    print('explanations:', {'pl': sum(1 for q in questions if q['explanation']), **{k: sum(1 for e in v.values() if e.get('explanation')) for k, v in translations.items()}}, 'from files:', explained)
    print('by topic:')
    for t in topics:
        print(f"  {t['id']:<22} {t['category']:<10} {t['questionCount']:>5}")
    per_lic = Counter()
    for q in questions:
        for l in q['licences']:
            per_lic[l] += 1
    print('per licence:', dict(sorted(per_lic.items(), key=lambda x: LICENCE_ORDER.index(x[0]))))
    # Paper buckets for B — the mock generator needs every (class, points) bucket non-empty.
    b = [q for q in questions if 'B' in q['licences']]
    buckets = Counter((q['category'], q['points']) for q in b)
    print('B buckets:', dict(sorted(buckets.items())))


if __name__ == '__main__':
    main()
